#!/usr/bin/env python3
"""Crawls CS2 workshop search pages, scores every map like the extension does and writes spam authors to spam_authors.json and blocklist.js.
Usage: python3 -I tools/crawl.py [pages per search, default 5]"""
import json, re, sys, time, urllib.request, urllib.parse
from collections import defaultdict

PAGES = int(sys.argv[1]) if len(sys.argv) > 1 else 5
QUERIES = ['', 'awp', 'mirage', 'dust2', 'dust 2', 'models', 'cheats', 'online', 'bhop', 'war', 'random', 'skins', 'brainrot', 'walls']
SORTS = ['trend', 'mostrecent']
HIDE = 70
SPAM = [r'disable_workshop_command_filtering', r'auto-?connect', r'параметры запуска', r'подключ',
        r'connect\s+\d{1,3}(\.\d{1,3}){3}', r'\d{1,3}(\.\d{1,3}){3}:\d{4,5}']
KW = ['models', 'online', 'cheats', 'skins', 'random', 'bhop', 'brainrot', 'walls', 'wars', 'war ']
cyr = lambda s: len(re.findall('[Ѐ-ӿ]', s))

def score(it):
    t, d = it.get('title', ''), it.get('short_description', '')
    sc, why = 0, []
    if cyr(d) >= 8: sc += 70; why.append('kyr-desc')
    if cyr(t) >= 3: sc += 30; why.append('kyr-title')
    if any(re.search(p, d, re.I) for p in SPAM): sc += 80; why.append('spam-phrase')
    h = [k for k in KW if k in t.lower() + ' ']
    if h: sc += min(30, 15 * len(h)); why.append('kw:' + ','.join(h))
    return sc, why

def collect(o, out, depth=0):
    if depth > 12: return
    if isinstance(o, str):
        if len(o) > 2 and o[0] in '{[' and 'publishedfileid' in o:
            try: collect(json.loads(o), out, depth + 1)
            except Exception: pass
    elif isinstance(o, list):
        for v in o: collect(v, out, depth + 1)
    elif isinstance(o, dict):
        if 'publishedfileid' in o and 'title' in o: out[o['publishedfileid']] = o
        else:
            for v in o.values(): collect(v, out, depth + 1)

def fetch(q, sort, page):
    params = {'appid': 730, 'searchtext': q, 'browsesort': sort, 'p': page, 'l': 'english'}
    url = 'https://steamcommunity.com/workshop/browse/?' + urllib.parse.urlencode(params)
    req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0', 'Accept-Language': 'en'})
    html = urllib.request.urlopen(req, timeout=30).read().decode('utf8', 'replace')
    m = re.search(r'id="valve-ssr-data"[^>]*>(.*?)</script>', html, re.S)
    out = {}
    if m: collect(json.loads(m.group(1)), out)
    return out

items = {}
for q in QUERIES:
    for sort in SORTS:
        for p in range(1, PAGES + 1):
            try: got = fetch(q, sort, p)
            except Exception as e:
                print('Error', q, sort, p, e); break
            new = len(set(got) - set(items))
            items.update(got)
            print(f'{q or "(leer)":10} {sort:10} p{p}: {len(got)} Maps, {new} neu, gesamt {len(items)}', flush=True)
            if not got: break
            time.sleep(1.5)

authors = defaultdict(lambda: {'maps': 0, 'spam': 0, 'titles': []})
flagged = 0
for it in items.values():
    sc, why = score(it)
    a = authors[it['creator']]
    a['maps'] += 1
    if sc >= HIDE:
        flagged += 1; a['spam'] += 1
        if len(a['titles']) < 3: a['titles'].append(it['title'])
spam_authors = {k: v for k, v in authors.items() if v['spam'] > 0}
# author counts as spammer if at least half of the found maps are flagged
blocklist = sorted(k for k, v in spam_authors.items() if v['spam'] * 2 >= v['maps'])
json.dump({'blockedAuthors': blocklist, 'details': spam_authors}, open('../spam_authors.json', 'w'), ensure_ascii=False, indent=1)
open('../blocklist.js', 'w').write('// Generated by tools/crawl.py\nconst CS2WF_SEED = ' + json.dumps(blocklist) + ';\n')
print(f'\n{len(items)} maps, {flagged} flagged, {len(spam_authors)} authors with hits, {len(blocklist)} blocked -> spam_authors.json, blocklist.js')
legit = [(k, v) for k, v in spam_authors.items() if k not in blocklist]
if legit:
    print('Borderline authors (not blocked, please review):')
    for k, v in legit: print(' ', k, v['spam'], '/', v['maps'], v['titles'])
